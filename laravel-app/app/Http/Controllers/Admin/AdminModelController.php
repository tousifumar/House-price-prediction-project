<?php

namespace App\Http\Controllers\Admin;

use App\Http\Controllers\Controller;
use App\Models\Dataset;
use App\Models\MlModel;
use Illuminate\Http\RedirectResponse;
use Illuminate\Http\Request;
use Illuminate\Support\Facades\File;
use Illuminate\Support\Facades\Http;
use Illuminate\Support\Facades\Log;
use Illuminate\View\View;
use Symfony\Component\Process\Process;

class AdminModelController extends Controller
{
    public function index(): View
    {
        $models = MlModel::with('dataset')->latest()->get();
        $activeModel = MlModel::where('status', 'active')->first();
        $datasets = Dataset::latest()->get();

        return view('admin.models.index', compact('models', 'activeModel', 'datasets'));
    }

    public function activate(int $id): RedirectResponse
    {
        $targetModel = MlModel::findOrFail($id);

        // Deactivate all models
        MlModel::where('status', 'active')->update(['status' => 'inactive']);

        // Activate selected model
        $targetModel->status = 'active';
        $targetModel->save();

        // Hot-reload model in FastAPI microservice if running
        $mlUrl = rtrim(env('ML_SERVICE_URL', 'http://127.0.0.1:8001'), '/');
        try {
            Http::timeout(5)->post("{$mlUrl}/reload-model");
        } catch (\Throwable $e) {
            Log::info("Could not hot-reload ML microservice automatically: {$e->getMessage()}");
        }

        return back()->with('success', "Model '{$targetModel->name} ({$targetModel->version})' is now active in production.");
    }

    public function train(Request $request): RedirectResponse
    {
        $request->validate([
            'dataset_id' => 'nullable|exists:datasets,id',
            'algorithm' => 'nullable|string|in:GradientBoosting,XGBoost,RandomForest,LinearRegression',
        ]);

        $dataset = null;
        if ($request->filled('dataset_id')) {
            $dataset = Dataset::find($request->dataset_id);
        }

        // Script path
        $scriptPath = base_path('../ml-service/training/train.py');

        if (!File::exists($scriptPath)) {
            return back()->with('error', 'Training script ml-service/training/train.py not found.');
        }

        $command = ['python', $scriptPath];
        if ($dataset && File::exists($dataset->file_path)) {
            $command[] = '--dataset';
            $command[] = $dataset->file_path;
        }

        $process = new Process($command);
        $process->setTimeout(180); // 3 minutes timeout

        try {
            $process->run();

            if (!$process->isSuccessful()) {
                Log::error('ML Training failed: ' . $process->getErrorOutput());
                return back()->with('error', 'Model training encountered an error. Check application logs.');
            }

            // Read model metadata generated by train.py
            $metadataPath = base_path('../ml-service/models/model_metadata.json');
            if (File::exists($metadataPath)) {
                $meta = json_decode(File::get($metadataPath), true);

                $newVersion = 'v' . date('Ymd.His');
                $newModel = MlModel::create([
                    'name' => 'Bangalore Housing Valuation Model',
                    'version' => $newVersion,
                    'algorithm' => $meta['algorithm'] ?? 'Gradient Boosting Regressor',
                    'dataset_id' => $dataset ? $dataset->id : null,
                    'model_path' => 'ml-service/models/active_model.joblib',
                    'preprocessor_path' => 'ml-service/models/preprocessor_v1.0.joblib',
                    'mae' => (float) ($meta['test_metrics']['mae'] ?? 725000),
                    'rmse' => (float) ($meta['test_metrics']['rmse'] ?? 1094000),
                    'r2_score' => (float) ($meta['test_metrics']['r2_score'] ?? 0.988),
                    'mape' => (float) ($meta['test_metrics']['mape'] ?? 4.70),
                    'hyperparameters' => $meta['hyperparameters'] ?? [],
                    'feature_importance' => $meta['feature_importance'] ?? [],
                    'status' => 'inactive', // Admin can review and activate
                    'trained_at' => now(),
                ]);

                return back()->with('success', "New model version {$newVersion} trained successfully (R²: " . round($newModel->r2_score * 100, 2) . "%). You may now review metrics and activate it.");
            }

            return back()->with('success', 'Model training completed successfully.');
        } catch (\Throwable $e) {
            Log::error('ML Training exception: ' . $e->getMessage());
            return back()->with('error', 'Training process error: ' . $e->getMessage());
        }
    }
}
